#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

SEED="${SEED:-2424}"
METHODS="${METHODS:-hg_ms}"
TAG="${TAG:-large_qwen25_32b_direct_lambda_diag_$(date +%Y%m%d_%H%M%S)}"
OUTPUT_ROOT="${OUTPUT_ROOT:-/scratch/${USER}/${TAG}}"

MODEL_NAME="${MODEL_NAME:-Qwen/Qwen2.5-32B-Instruct}"
REFERENCE_MODEL_NAME="${REFERENCE_MODEL_NAME:-Qwen/Qwen2.5-7B-Instruct}"
MAX_LENGTH="${MAX_LENGTH:-512}"

# This is a diagnostic, not a result run. Keep it cheap, but make the
# hypergradient signal strong enough that a broken theta path fails loudly.
REWEIGHT_TRAIN_PER_SOURCE="${REWEIGHT_TRAIN_PER_SOURCE:-80}"
VAL_PER_SOURCE="${VAL_PER_SOURCE:-30}"
REWEIGHT_STEPS="${REWEIGHT_STEPS:-20}"
REWEIGHT_WALL_CLOCK_SECONDS="${REWEIGHT_WALL_CLOCK_SECONDS:-1800}"
PER_SOURCE_BATCH="${PER_SOURCE_BATCH:-1}"
VAL_BATCH_SIZE="${VAL_BATCH_SIZE:-2}"
SELECTION_VAL_BATCH_SIZE="${SELECTION_VAL_BATCH_SIZE:-2}"
SELECTION_VAL_BATCHES="${SELECTION_VAL_BATCHES:-1}"
HYPERGRAD_VAL_BATCHES="${HYPERGRAD_VAL_BATCHES:-1}"
INNER_STEPS="${INNER_STEPS:-2}"
SELECTION_INNER_STEPS="${SELECTION_INNER_STEPS:-2}"
HYPERGRAD_INNER_STEPS="${HYPERGRAD_INNER_STEPS:-2}"
M_BRANCHES="${M_BRANCHES:-2}"
BRANCH_NOISE_STD="${BRANCH_NOISE_STD:-1e-3}"
REWEIGHT_MODEL_LR="${REWEIGHT_MODEL_LR:-5e-4}"
REWEIGHT_OUTER_LR="${REWEIGHT_OUTER_LR:-0.2}"
THETA_OPTIMIZER="${THETA_OPTIMIZER:-adam}"
SCALEBIO_ALPHA="${SCALEBIO_ALPHA:-100.0}"
TUNE_EVERY="${TUNE_EVERY:-5}"
LORA_R="${LORA_R:-2}"
LORA_ALPHA="${LORA_ALPHA:-4}"
LORA_DROPOUT="${LORA_DROPOUT:-0.0}"
MIN_LAMBDA_MOVEMENT="${MIN_LAMBDA_MOVEMENT:-1e-4}"
MIN_CENTERED_GRAD_NORM="${MIN_CENTERED_GRAD_NORM:-1e-10}"

VAL_KINDS_SPEC="${VAL_KINDS_SPEC:-gsm8k}"
CACHE_PATH="${CACHE_PATH:-/scratch/${USER}/hypergrad_exact_cache/qwen25_32b_seed${SEED}_train${REWEIGHT_TRAIN_PER_SOURCE}_val${VAL_PER_SOURCE}_tov4.0_vov1.2.json}"

mkdir -p "${OUTPUT_ROOT}" /scratch/"${USER}"/slurm

echo "Submitting direct 32B lambda-movement diagnostic"
echo "  output root: ${OUTPUT_ROOT}"
echo "  methods: ${METHODS}"
echo "  model: ${MODEL_NAME}"
echo "  max_length: ${MAX_LENGTH}"
echo "  steps: ${REWEIGHT_STEPS}"
echo "  lambda movement threshold: ${MIN_LAMBDA_MOVEMENT}"

submit_one() {
  local method="$1"
  local run_name="${method}_qwen25_32b_direct_lambda_diag"
  local shared_cache_root="/scratch/${USER}/hf_cache_jobs/qwen25_32b/${method}_qwen25_32b_smoke"
  local cache_root="${HF_CACHE_ROOT:-${shared_cache_root}}"
  local job_name="lg32_${method}_lambda_diag"

  sbatch \
    --job-name="${job_name}" \
    --time=03:00:00 \
    --export=ALL,\
ROOT_DIR="${SCRIPT_DIR}",\
METHOD="${method}",\
SEED="${SEED}",\
MODEL_NAME="${MODEL_NAME}",\
REFERENCE_MODEL_NAME="${REFERENCE_MODEL_NAME}",\
OUTPUT_ROOT="${OUTPUT_ROOT}",\
RUN_NAME="${run_name}",\
HF_CACHE_ROOT="${cache_root}",\
CACHE_PATH="${CACHE_PATH}",\
ALLOW_TRAIN_SHORTFALL=1,\
STOP_AFTER_REWEIGHT=1,\
LOCAL_MODEL_ONLY=1,\
VAL_KINDS_SPEC="${VAL_KINDS_SPEC}",\
MAX_LENGTH="${MAX_LENGTH}",\
REWEIGHT_TRAIN_PER_SOURCE="${REWEIGHT_TRAIN_PER_SOURCE}",\
VAL_PER_SOURCE="${VAL_PER_SOURCE}",\
TRAIN_RAW_OVERSAMPLE=4.0,\
VAL_RAW_OVERSAMPLE=1.2,\
REWEIGHT_STEPS="${REWEIGHT_STEPS}",\
REWEIGHT_WALL_CLOCK_SECONDS="${REWEIGHT_WALL_CLOCK_SECONDS}",\
PER_SOURCE_BATCH="${PER_SOURCE_BATCH}",\
VAL_BATCH_SIZE="${VAL_BATCH_SIZE}",\
SELECTION_VAL_BATCH_SIZE="${SELECTION_VAL_BATCH_SIZE}",\
SELECTION_VAL_BATCHES="${SELECTION_VAL_BATCHES}",\
HYPERGRAD_VAL_BATCHES="${HYPERGRAD_VAL_BATCHES}",\
REUSE_SELECTION_BATCHES_FOR_HYPERGRAD=0,\
INNER_STEPS="${INNER_STEPS}",\
SELECTION_INNER_STEPS="${SELECTION_INNER_STEPS}",\
HYPERGRAD_INNER_STEPS="${HYPERGRAD_INNER_STEPS}",\
M_BRANCHES="${M_BRANCHES}",\
BRANCH_NOISE_STD="${BRANCH_NOISE_STD}",\
REWEIGHT_MODEL_LR="${REWEIGHT_MODEL_LR}",\
REWEIGHT_OUTER_LR="${REWEIGHT_OUTER_LR}",\
THETA_OPTIMIZER="${THETA_OPTIMIZER}",\
SCALEBIO_ALPHA="${SCALEBIO_ALPHA}",\
TUNE_EVERY="${TUNE_EVERY}",\
LORA_R="${LORA_R}",\
LORA_ALPHA="${LORA_ALPHA}",\
LORA_DROPOUT="${LORA_DROPOUT}",\
MIN_LAMBDA_MOVEMENT="${MIN_LAMBDA_MOVEMENT}",\
MIN_CENTERED_GRAD_NORM="${MIN_CENTERED_GRAD_NORM}" \
    "${SCRIPT_DIR}/run_exact_math_reasoning.sbatch"
}

for method in ${METHODS}; do
  submit_one "${method}"
done
