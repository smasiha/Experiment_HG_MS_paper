#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="${ROOT_DIR:-${SCRIPT_DIR}}"
METHOD="${METHOD:-hg_ms}"
MODEL_NAME="${MODEL_NAME:-Qwen/Qwen2.5-0.5B-Instruct}"
SEED="${SEED:-2424}"
REWEIGHT_STEPS="${REWEIGHT_STEPS:-10}"
STOP_AFTER_REWEIGHT="${STOP_AFTER_REWEIGHT:-1}"

cd "${ROOT_DIR}"

sbatch \
  --export=ALL,METHOD="${METHOD}",MODEL_NAME="${MODEL_NAME}",SEED="${SEED}",STOP_AFTER_REWEIGHT="${STOP_AFTER_REWEIGHT}",REWEIGHT_STEPS="${REWEIGHT_STEPS}",OUTPUT_ROOT="${OUTPUT_ROOT_INSTRUCTION:-/scratch/${USER}/realworld_instruction_hg_small}",MAX_LENGTH="${MAX_LENGTH_INSTRUCTION:-256}",VAL_BATCH_SIZE="${VAL_BATCH_SIZE_INSTRUCTION:-1}",SELECTION_VAL_BATCH_SIZE="${SELECTION_VAL_BATCH_SIZE_INSTRUCTION:-1}",EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE_INSTRUCTION:-1}",REWEIGHT_MODEL_LR="${REWEIGHT_MODEL_LR_INSTRUCTION:-1e-4}",REWEIGHT_OUTER_LR="${REWEIGHT_OUTER_LR_INSTRUCTION:-0.1}",BRANCH_NOISE_STD="${BRANCH_NOISE_STD_INSTRUCTION:-0}" \
  run_real_world_instruction.sbatch

sbatch \
  --export=ALL,METHOD="${METHOD}",MODEL_NAME="${MODEL_NAME}",SEED="${SEED}",STOP_AFTER_REWEIGHT="${STOP_AFTER_REWEIGHT}",REWEIGHT_STEPS="${REWEIGHT_STEPS}",OUTPUT_ROOT="${OUTPUT_ROOT_MATH:-/scratch/${USER}/realworld_math_hg_small}",MAX_LENGTH="${MAX_LENGTH_MATH:-512}",VAL_BATCH_SIZE="${VAL_BATCH_SIZE_MATH:-1}",SELECTION_VAL_BATCH_SIZE="${SELECTION_VAL_BATCH_SIZE_MATH:-1}",EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE_MATH:-1}",REWEIGHT_MODEL_LR="${REWEIGHT_MODEL_LR_MATH:-1e-4}",REWEIGHT_OUTER_LR="${REWEIGHT_OUTER_LR_MATH:-0.1}",BRANCH_NOISE_STD="${BRANCH_NOISE_STD_MATH:-0}",REWEIGHT_TRAIN_PER_SOURCE="${REWEIGHT_TRAIN_PER_SOURCE_MATH:-500}",ALLOW_TRAIN_SHORTFALL=1 \
  run_exact_math_reasoning.sbatch
